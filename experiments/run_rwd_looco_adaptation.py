# ---------------------------------------------------------------------------
# Lightweight domain wrapper  (duck-typed to match DomainDataset interface)
# ---------------------------------------------------------------------------

@dataclass
class _DS:
    """Minimal domain object expected by adaptation_methods.py."""
    x: np.ndarray         # (n, p) standardised covariates
    y: np.ndarray         # (n,)   binary outcome
    domain_id: int
    n: int


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _binary_label(t: np.ndarray, delta: np.ndarray, tau: float) -> np.ndarray:
    return ((t <= tau) & (delta == 1)).astype(int)


def _build_ds(c: dict, tau: float, scaler: StandardScaler, src_med: np.ndarray) -> _DS:
    """Impute, scale and wrap one center's data as _DS."""
    X_imp = np.where(np.isnan(c["X"]), src_med, c["X"])
    X_s   = scaler.transform(X_imp)
    y     = _binary_label(c["t"], c["delta"], tau)
    return _DS(x=X_s, y=y, domain_id=c["center_id"], n=len(y))


def _augment_source(
    source_centers_imp: list[dict],
    tau: float,
    nu: float,
    scaler: StandardScaler,
    src_med: np.ndarray,
    aug_factor: int,
    k_total: int = 6,
    seed: int = 42,
) -> list[_DS]:
    """
    Augment each source center with synthetic data generated by the
    data-grounded Weibull PH generator.

    For each source center:
      - fit per-center DomainParams (A, w shared across sources)
      - generate aug_factor * n_d synthetic samples
      - stack real + synthetic into a single _DS

    Returns list of augmented _DS objects (one per source center).
    """
    # Fit shared A and w from source
    A, w, source_params, _ = fit_reference_generator(
        source_centers=source_centers_imp, k_total=k_total, tau=tau, nu=nu,
    )
    p = source_centers_imp[0]["X"].shape[1]
    base = BaseParams(k_inv=k_total, k_spu=0, p=p, tau=tau, seed=seed)
    gen  = SyntheticGenerator(base, shared_A_inv=A, shared_A_spu=None)

    aug_ds_list = []
    for dp, sc in zip(source_params, source_centers_imp):
        # Real data in standardised space
        X_real_s = scaler.transform(sc["X"])
        y_real   = _binary_label(sc["t"], sc["delta"], tau)

        # Synthetic: aug_factor × n_real samples
        from dataclasses import replace as _replace
        dp_aug   = _replace(dp, n=aug_factor * sc["n"])
        synth    = gen.generate_domain(dp_aug, seed=seed + sc["center_id"] * 7)
        X_synth  = synth.x     # (n_aug, p) — already in standardised space
        y_synth  = synth.y     # (n_aug,)

        X_comb = np.vstack([X_real_s, X_synth])
        y_comb = np.concatenate([y_real, y_synth])
        aug_ds_list.append(
            _DS(x=X_comb, y=y_comb, domain_id=sc["center_id"], n=len(y_comb))
        )
    return aug_ds_list


def _synth_only_source(
    source_centers_imp: list[dict],
    tau: float,
    nu: float,
    scaler: StandardScaler,
    n_per_center: int,
    k_total: int = 6,
    seed: int = 42,
) -> list[_DS]:
    """
    Source = purely synthetic data, one _DS per center.
    No real source data mixed in — clean generator distribution.
    n_per_center: how many synthetic samples per center.
    """
    A, w, source_params, _ = fit_reference_generator(
        source_centers=source_centers_imp, k_total=k_total, tau=tau, nu=nu,
    )
    p = source_centers_imp[0]["X"].shape[1]
    base = BaseParams(k_inv=k_total, k_spu=0, p=p, tau=tau, seed=seed)
    gen  = SyntheticGenerator(base, shared_A_inv=A, shared_A_spu=None)

    from dataclasses import replace as _replace
    synth_ds_list = []
    for dp, sc in zip(source_params, source_centers_imp):
        dp_s  = _replace(dp, n=n_per_center)
        synth = gen.generate_domain(dp_s, seed=seed + sc["center_id"] * 7)
        synth_ds_list.append(
            _DS(x=synth.x, y=synth.y, domain_id=sc["center_id"], n=n_per_center)
        )
    return synth_ds_list


def _pooled_source(src_ds: list[_DS]) -> list[_DS]:
    """
    Collapse all source domains into one single _DS.
    DANN then sees one source distribution vs target (simpler alignment problem).
    """
    X = np.vstack([d.x for d in src_ds])
    y = np.concatenate([d.y for d in src_ds])
    return [_DS(x=X, y=y, domain_id=0, n=len(y))]


# ---------------------------------------------------------------------------
# Main LOOCO loop
# ---------------------------------------------------------------------------

def run_rwd_looco_adaptation(
    features: int = 22,
    tau: float = 12.0,
    nu: float = 1.5,
    k_total: int = 6,
    run_dann: bool = True,
    run_irm: bool = True,
    run_cdan: bool = False,
    aug_factor: int = 0,
    run_synth_only: bool = False,
    run_dann_pooled: bool = False,
    verbose: bool = True,
    out_dir: str = "outputs/tables/",
) -> pd.DataFrame:
    """
    Parameters
    ----------
    features        : 11 (original registry) or 22 (registry_rwd extended features)
    tau             : prediction horizon in months
    nu              : Weibull shape for augmentation generator
    k_total         : latent dimensions for augmentation generator
    run_dann        : include DANN with real per-center source
    run_irm         : include IRM
    run_cdan        : include CDAN (optional, off by default)
    aug_factor      : if > 0, also run DANN+aug (real + synthetic source)
    run_synth_only  : DANN where source = purely synthetic (no real source mixed in)
    run_dann_pooled : DANN where all source centers are collapsed into one domain
    """
    # --- load data ---
    if features == 22:
        from data import registry_rwd as reg
        centers, feat_names = reg.load_all_centers()
        center_names = reg.CENTER_NAMES
    else:
        from data import registry as reg
        from data.loader import load_all_centers
        centers, feat_names = load_all_centers(registry_module=reg)
        center_names = getattr(reg, "CENTER_NAMES", {c["center_id"]: str(c["center_id"]) for c in centers})

    D = len(centers)
    p = centers[0]["X"].shape[1]

    if verbose:
        extras = []
        if aug_factor > 0:    extras.append(f"aug_factor={aug_factor}")
        if run_synth_only:    extras.append("synth_only")
        if run_dann_pooled:   extras.append("dann_pooled")
        extra_str = ("  " + "  ".join(extras)) if extras else ""
        print(f"=== RWD LOOCO Adaptation ===")
        print(f"  D={D} centers, p={p} features ({features}-feat set), τ={tau} months{extra_str}\n")

    need_dann = run_dann or aug_factor > 0 or run_synth_only or run_dann_pooled

    # lazy imports (TF only loaded if DANN/CDAN requested)
    from experiments.baselines import fit_all_observed, fit_all_observed_mlp
    from experiments.adaptation_methods import fit_coral, fit_irm as _fit_irm
    if need_dann:
        from experiments.adaptation_methods import fit_dann
    if run_cdan:
        from experiments.adaptation_methods import fit_cdan

    rows = []

    for held_idx in range(D):
        held   = centers[held_idx]
        src_cs = [c for i, c in enumerate(centers) if i != held_idx]
        hid    = held["center_id"]
        hname  = center_names.get(hid, str(hid))

        # Impute and scale on source
        X_src_pool = np.vstack([c["X"] for c in src_cs])
        _, src_med = impute_median(X_src_pool)

        X_src_imp  = np.where(np.isnan(X_src_pool), src_med, X_src_pool)
        scaler = StandardScaler()
        scaler.fit(X_src_imp)

        src_ds  = [_build_ds(c, tau, scaler, src_med) for c in src_cs]
        tgt_ds  = _build_ds(held, tau, scaler, src_med)

        n_events = int(tgt_ds.y.sum())
        n_total  = tgt_ds.n
        prev     = float(tgt_ds.y.mean())

        if verbose:
            print(f"--- {hname:6s}  n={n_total:4d}  events={n_events:3d}  prev={prev:.2f} ---")

        # -- LR ERM --
        with warnings.catch_warnings():
            warnings.filterwarnings("ignore")
            r = fit_all_observed(src_ds, tgt_ds)
        lr_auroc = r["target"]["auroc"]

        # -- MLP ERM --
        with warnings.catch_warnings():
            warnings.filterwarnings("ignore")
            r = fit_all_observed_mlp(src_ds, tgt_ds)
        mlp_auroc = r["target"]["auroc"]

        # -- CORAL --
        with warnings.catch_warnings():
            warnings.filterwarnings("ignore")
            r = fit_coral(src_ds, tgt_ds, seed=42)
        coral_auroc = r["target"]["auroc"]

        # -- IRM --
        irm_auroc = float("nan")
        if run_irm:
            with warnings.catch_warnings():
                warnings.filterwarnings("ignore")
                r = _fit_irm(src_ds, tgt_ds, seed=42)
            irm_auroc = r["target"]["auroc"]

        # -- DANN --
        dann_auroc = float("nan")
        if run_dann:
            with warnings.catch_warnings():
                warnings.filterwarnings("ignore")
                r = fit_dann(src_ds, tgt_ds, seed=42)
            dann_auroc = r["target"]["auroc"]

        # -- CDAN --
        cdan_auroc = float("nan")
        if run_cdan:
            with warnings.catch_warnings():
                warnings.filterwarnings("ignore")
                r = fit_cdan(src_ds, tgt_ds, seed=42)
            cdan_auroc = r["target"]["auroc"]

        # -- DANN + augmentation (real + synthetic) --
        dann_aug_auroc = float("nan")
        if aug_factor > 0:
            src_cs_imp = [{**c, "X": np.where(np.isnan(c["X"]), src_med, c["X"])}
                          for c in src_cs]
            aug_src_ds = _augment_source(
                source_centers_imp=src_cs_imp,
                tau=tau, nu=nu, scaler=scaler, src_med=src_med,
                aug_factor=aug_factor, k_total=k_total, seed=42,
            )
            with warnings.catch_warnings():
                warnings.filterwarnings("ignore")
                r = fit_dann(aug_src_ds, tgt_ds, seed=42)
            dann_aug_auroc = r["target"]["auroc"]

        # -- DANN + purely synthetic source --
        dann_synth_auroc = float("nan")
        if run_synth_only:
            src_cs_imp = [{**c, "X": np.where(np.isnan(c["X"]), src_med, c["X"])}
                          for c in src_cs]
            n_synth_per = int(np.mean([c["n"] for c in src_cs]))
            synth_src_ds = _synth_only_source(
                source_centers_imp=src_cs_imp,
                tau=tau, nu=nu, scaler=scaler,
                n_per_center=n_synth_per, k_total=k_total, seed=42,
            )
            with warnings.catch_warnings():
                warnings.filterwarnings("ignore")
                r = fit_dann(synth_src_ds, tgt_ds, seed=42)
            dann_synth_auroc = r["target"]["auroc"]

        # -- DANN + all source pooled into one domain --
        dann_pool_auroc = float("nan")
        if run_dann_pooled:
            pooled_src = _pooled_source(src_ds)
            with warnings.catch_warnings():
                warnings.filterwarnings("ignore")
                r = fit_dann(pooled_src, tgt_ds, seed=42)
            dann_pool_auroc = r["target"]["auroc"]

        row = {
            "center":       hname,
            "n":            n_total,
            "events":       n_events,
            "prev":         round(prev, 3),
            "lr_erm":       lr_auroc,
            "mlp_erm":      mlp_auroc,
            "coral":        coral_auroc,
            "irm":          irm_auroc,
            "dann":         dann_auroc,
            "dann_aug":     dann_aug_auroc,
            "dann_synth":   dann_synth_auroc,
            "dann_pooled":  dann_pool_auroc,
            "cdan":         cdan_auroc,
        }
        rows.append(row)

        if verbose:
            extra_vals = []
            if aug_factor > 0:    extra_vals.append(f"DANN+aug={dann_aug_auroc:.4f}")
            if run_synth_only:    extra_vals.append(f"DANN+synth={dann_synth_auroc:.4f}")
            if run_dann_pooled:   extra_vals.append(f"DANN+pool={dann_pool_auroc:.4f}")
            extra_str = ("  " + "  ".join(extra_vals)) if extra_vals else ""
            print(
                f"  LR={lr_auroc:.4f}  MLP={mlp_auroc:.4f}  "
                f"CORAL={coral_auroc:.4f}  IRM={irm_auroc:.4f}  "
                f"DANN={dann_auroc:.4f}{extra_str}"
            )

    df = pd.DataFrame(rows)

    metric_cols = ["lr_erm", "mlp_erm", "coral", "irm", "dann",
                   "dann_aug", "dann_synth", "dann_pooled", "cdan"]
    metric_cols = [c for c in metric_cols if c in df.columns]
    mean_row = df[metric_cols].mean()

    if verbose:
        print("\n--- Mean AUROC across centers ---")
        print(mean_row.round(4).to_string())
        print("\nGain vs LR ERM:")
        delta = mean_row - mean_row["lr_erm"]
        print(delta.round(4).to_string())
        print()

    # Save
    out_path = Path(out_dir)
    out_path.mkdir(parents=True, exist_ok=True)
    aug_tag = f"_aug{aug_factor}" if aug_factor > 0 else ""
    fname = f"rwd_looco_adaptation_{features}feat{aug_tag}.csv"
    df.to_csv(out_path / fname, index=False)
    if verbose:
        print(f"Saved → {out_path / fname}")

    return df


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def _parse():
    p = argparse.ArgumentParser(description="LOOCO adaptation on real RWD")
    p.add_argument("--features", type=int, choices=[11, 22], default=22,
                   help="feature set size (default 22)")
    p.add_argument("--tau",      type=float, default=12.0)
    p.add_argument("--no_dann",      action="store_true", help="skip DANN")
    p.add_argument("--no_irm",       action="store_true", help="skip IRM")
    p.add_argument("--cdan",         action="store_true", help="include CDAN")
    p.add_argument("--aug_factor",   type=int, default=0,
                   help="if >0, run DANN+aug with real+synthetic source (e.g. 5)")
    p.add_argument("--synth_only",   action="store_true",
                   help="run DANN with purely synthetic source (no real source)")
    p.add_argument("--dann_pooled",  action="store_true",
                   help="run DANN with all source centers collapsed into one domain")
    p.add_argument("--k_total",      type=int, default=6, help="latent dims for augmentation")
    p.add_argument("--out_dir",      default="outputs/tables/")
    return p.parse_args()


if __name__ == "__main__":
    args = _parse()
    run_rwd_looco_adaptation(
        features=args.features,
        tau=args.tau,
        k_total=args.k_total,
        run_dann=not args.no_dann,
        run_irm=not args.no_irm,
        run_cdan=args.cdan,
        aug_factor=args.aug_factor,
        run_synth_only=args.synth_only,
        run_dann_pooled=args.dann_pooled,
        out_dir=args.out_dir,
    )
