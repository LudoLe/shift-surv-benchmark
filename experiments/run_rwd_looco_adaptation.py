"""
LOOCO (Leave-One-Center-Out) domain adaptation on real RWD data.

For each center d:
  - Source: all other D-1 centers (pooled as separate domain objects)
  - Target: held-out center d

Methods evaluated:
  - LR ERM     : logistic regression on pooled source X
  - MLP ERM    : MLP on pooled source X
  - CORAL      : covariance alignment + LR
  - DANN       : domain-adversarial neural network
  - IRM        : invariant risk minimisation
  - DANN+aug   : DANN with source augmented via data-grounded generator

Feature set: 22 features (registry_rwd) or 11 features (registry).

Usage
-----
  cd /Users/ludole/Desktop/SHIFT-SURV
  python -m experiments.run_rwd_looco_adaptation [--features {11,22}] [--no_dann] [--no_irm]
  python -m experiments.run_rwd_looco_adaptation --aug_factor 5   # enable DANN+aug
"""

