"""
Semi-synthetic concept shift validation on GBSG2.

Design
------
Real covariates X from GBSG2, survival times T generated synthetically with
known shift type → ground truth controlled, covariate distributions realistic.

Pseudo-centers: split GBSG2 by (horTh × menostat) → 4 groups
  no_Pre  (n=231), no_Post (n=209), yes_Post (n=187), yes_Pre (n=59)

Semi-synthetic data generation:
  1. Fit loading matrix A and risk weights w_src on source centers (real X, synth T)
  2. Estimate per-center λ₀_d from source survival times
  3. For the held-out center: generate T_real using w_src (no concept shift)
     and T_shifted using w_rotated(θ) (injected concept shift)
  4. "Real target" = held-out X + T_real or T_shifted
  5. "Synthetic target" = generated by our tool (assumes w_src, estimates μ_d, λ₀)

Key validation:
  gap = AUROC_synth - AUROC_real
  - No concept shift (θ=0):   gap should be small and stable
  - Concept shift  (θ>0):     gap should grow with θ

This directly addresses: "non dovremmo sapere che tipo di shift c'è per validarlo?"
→ here we DO know because we injected it, on real covariate distributions.
"""

from __future__ import annotations
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score
from sklearn.preprocessing import StandardScaler
import warnings
from sklearn.exceptions import ConvergenceWarning

from sksurv.datasets import load_gbsg2

from generator.base_generator import SyntheticGenerator
from generator.parameters import BaseParams, DomainParams
from generator.fitting import (
    fit_loading_matrix, fit_risk_weights,
    fit_lambda0, _km_at_tau,
)


TAU   = 48.0     # months; GBSG2 times are in days → convert, or use raw
NU    = 1.5
K     = 4
M     = 20
N_SEEDS = 30
N_SYNTH = 300    # size of generated synthetic population for evaluation


def _load_gbsg2_centers():
    """Load GBSG2 and split into 4 pseudo-centers by horTh × menostat."""
    X_df, y_struct = load_gbsg2()

    # Convert time from days to months
    t_raw = y_struct["time"] / 30.44
    delta = y_struct["cens"].astype(int)

    # Encode categoricals as 0/1
    X_enc = X_df.copy()
    X_enc["horTh"]    = (X_df["horTh"]    == "yes").astype(float)
    X_enc["menostat"] = (X_df["menostat"] == "Post").astype(float)
    X_enc["tgrade"]   = X_df["tgrade"].map({"I": 0.0, "II": 1.0, "III": 2.0})
    X_num = X_enc.values.astype(float)

    group_label = (X_df["horTh"].astype(str) + "_" + X_df["menostat"].astype(str)).values

    centers = []
    for g in ["no_Pre", "no_Post", "yes_Post", "yes_Pre"]:
        mask = group_label == g
        centers.append({
            "center_id": g,
            "X": X_num[mask],
            "t": t_raw[mask],
            "delta": delta[mask],
            "n": int(mask.sum()),
        })
    return centers


def _binary_label(t, delta, tau=TAU):
    return ((t <= tau) & (delta == 1)).astype(int)


def _auroc(scores, y):
    if len(np.unique(y)) < 2 or np.isnan(scores).any():
        return float("nan")
    return float(roc_auc_score(y, scores))


def _rotate_w(w_src, theta, rng):
    norm = np.linalg.norm(w_src)
    e1   = w_src / norm
    v    = rng.standard_normal(len(w_src))
    v   -= np.dot(v, e1) * e1
    e2   = v / np.linalg.norm(v)
    return norm * (np.cos(theta) * e1 + np.sin(theta) * e2)


def _generate_survival_times(X_std, A, w, lambda0, nu, rng):
    """
    Generate Weibull PH survival times for patients with standardised features X_std.
    T = (-log(U) / (lambda0 * exp(eta)))^(1/nu)  where U ~ Uniform(0,1)
    All patients uncensored (we observe full T).
    """
    U_mat = X_std @ A
    mu_d  = U_mat.mean(axis=0)
    eta   = (U_mat - mu_d) @ w
    U_rv  = rng.uniform(0, 1, size=len(X_std))
    T     = (-np.log(U_rv + 1e-12) / (lambda0 * np.exp(eta))) ** (1.0 / nu)
    return np.clip(T, 0.01, None)


def _estimate_params_from_m(X_m_std, A, w_fit, t_m, d_m, lam0_fallback):
    U_m  = X_m_std @ A
    mu_d = U_m.mean(axis=0)
    eta_m = (U_m - mu_d) @ w_fit
    if d_m.sum() >= 3:
        km_s = _km_at_tau(t_m, d_m, TAU)
        km_p = float(np.clip(1 - km_s, 0.01, 0.99))
        try:
            lam = fit_lambda0(eta_m, km_p, tau=TAU, nu=NU)
        except Exception:
            lam = lam0_fallback
    else:
        lam = lam0_fallback
    return mu_d, lam


def run_semisynthetic_gbsg2(
    theta_grid=None,
    out_dir="outputs/tables/",
    out_prefix="semisynthetic_gbsg2",
    verbose=True,
    seed=42,
):
    if theta_grid is None:
        theta_grid = [0.0, np.pi/8, np.pi/4, 3*np.pi/8, np.pi/2]

    out_path = Path(out_dir)
    out_path.mkdir(parents=True, exist_ok=True)

    centers = _load_gbsg2_centers()

    if verbose:
        print("=== Semi-synthetic GBSG2 Concept Shift Validation ===\n")
        for c in centers:
            y = _binary_label(c["t"], c["delta"])
            print(f"  {c['center_id']}: n={c['n']}, event_rate={y.mean():.2f}")
        print()

    rows = []

    for held_idx in range(len(centers)):
        held = centers[held_idx]
        hid  = held["center_id"]
        sources = [c for i, c in enumerate(centers) if i != held_idx]

        # ── standardise on source pool ───────────────────────────────────────
        X_src_pool = np.vstack([c["X"] for c in sources])
        scaler = StandardScaler().fit(X_src_pool)
        X_src_std = scaler.transform(X_src_pool)
        X_held_std = scaler.transform(held["X"])

        # ── fit A and w_src on source (using real survival times) ────────────
        A_fit = fit_loading_matrix(X_src_std, K)
        y_src_pool = _binary_label(
            np.concatenate([c["t"] for c in sources]),
            np.concatenate([c["delta"] for c in sources]),
        )
        U_src = X_src_std @ A_fit
        w_src = fit_risk_weights(U_src, y_src_pool)

        # Per-source λ₀ estimates
        lam0_list = []
        for c in sources:
            X_s = scaler.transform(c["X"])
            U_s = X_s @ A_fit
            mu_s = U_s.mean(axis=0)
            eta_s = (U_s - mu_s) @ w_src
            if c["delta"].sum() >= 3:
                km_s = _km_at_tau(c["t"], c["delta"], TAU)
                km_p = float(np.clip(1 - km_s, 0.01, 0.99))
                try:
                    lam0_list.append(fit_lambda0(eta_s, km_p, tau=TAU, nu=NU))
                except Exception:
                    pass
        lam0_src_mean = float(np.mean(lam0_list)) if lam0_list else 0.02

        # ── source LR (fitted on synthetic data regenerated from w_src) ──────
        # We re-generate source survival times with known w_src so the generator
        # is self-consistent (X real, T synthetic from w_src)
        rng_gen = np.random.default_rng(seed + held_idx * 100)
        t_src_synth = _generate_survival_times(
            X_src_std, A_fit, w_src, lam0_src_mean, NU, rng_gen
        )
        y_src_synth = _binary_label(t_src_synth,
                                    np.ones(len(X_src_std), dtype=int))

        with warnings.catch_warnings():
            warnings.filterwarnings("ignore", category=ConvergenceWarning)
            lr_src = LogisticRegression(C=1.0, max_iter=1000,
                                        class_weight="balanced", random_state=0)
            lr_src.fit(X_src_std, y_src_synth)

        if verbose:
            print(f"--- Held-out: {hid} (n={held['n']}) ---")

        for theta in theta_grid:
            auroc_reals, auroc_synths = [], []

            for s in range(N_SEEDS):
                rng = np.random.default_rng(seed + held_idx * 1000 + s * 97 + int(theta * 1000))

                # Build target w (rotated if concept shift)
                w_tgt = _rotate_w(w_src, theta, rng) if theta > 0.0 else w_src.copy()

                # Target λ₀: same as source mean (only concept shift, no λ shift)
                lam0_tgt = lam0_src_mean

                # Generate T for held-out patients with target w
                t_tgt = _generate_survival_times(
                    X_held_std, A_fit, w_tgt, lam0_tgt, NU, rng
                )
                y_tgt_real = _binary_label(t_tgt, np.ones(len(X_held_std), dtype=int))

                if len(np.unique(y_tgt_real)) < 2:
                    continue

                # AUROC of source model on real target
                a_real = _auroc(lr_src.predict_proba(X_held_std)[:, 1], y_tgt_real)

                # Our tool: estimate μ_d, λ₀ from m patients
                idx_m  = rng.choice(held["n"], size=min(M, held["n"]//2), replace=False)
                X_m    = X_held_std[idx_m]
                t_m    = t_tgt[idx_m]
                d_m    = np.ones(len(idx_m), dtype=int)  # synth T fully observed

                mu_d_est, lam_est = _estimate_params_from_m(
                    X_m, A_fit, w_src, t_m, d_m, lam0_src_mean
                )

                # Generate synthetic target: w_src assumed (tool's assumption)
                X_synth_std, t_synth = [], []
                # Resample from held-out X with replacement → realistic covariates
                idx_synth = rng.choice(held["n"], size=N_SYNTH, replace=True)
                X_syn = X_held_std[idx_synth] - (X_held_std[idx_synth] @ A_fit).mean(axis=0) @ np.linalg.pinv(A_fit)
                # Simpler: just generate T from w_src, estimated λ₀, mu_d
                t_syn_raw = _generate_survival_times(
                    X_held_std[idx_synth], A_fit, w_src, lam_est, NU, rng
                )
                y_syn = _binary_label(t_syn_raw, np.ones(N_SYNTH, dtype=int))

                if len(np.unique(y_syn)) < 2:
                    continue

                a_synth = _auroc(
                    lr_src.predict_proba(X_held_std[idx_synth])[:, 1], y_syn
                )

                auroc_reals.append(a_real)
                auroc_synths.append(a_synth)

            a_r = float(np.nanmean(auroc_reals)) if auroc_reals else float("nan")
            a_s = float(np.nanmean(auroc_synths)) if auroc_synths else float("nan")
            gap = a_s - a_r

            rows.append({
                "center": hid,
                "theta": round(theta, 4),
                "theta_label": f"θ={theta/np.pi:.2f}π",
                "auroc_real": round(a_r, 4),
                "auroc_synth": round(a_s, 4),
                "gap": round(gap, 4),
            })

            if verbose:
                flag = " ← DETECTED" if gap > 0.10 else ""
                print(f"  θ={theta/np.pi:.2f}π  "
                      f"real={a_r:.4f}  synth={a_s:.4f}  gap={gap:+.4f}{flag}")

        if verbose:
            print()

    df = pd.DataFrame(rows)
    df.to_csv(out_path / f"{out_prefix}_results.csv", index=False)

    if verbose:
        print(f"Saved → {out_path}/{out_prefix}_results.csv\n")
        print("Mean gap by θ (averaged over centers):")
        pivot = df.groupby("theta")[["auroc_real","auroc_synth","gap"]].mean().round(4)
        pivot["theta_label"] = [f"θ={t/np.pi:.2f}π" for t in pivot.index]
        print(pivot[["theta_label","auroc_real","auroc_synth","gap"]].to_string(index=False))

    return df


if __name__ == "__main__":
    run_semisynthetic_gbsg2(verbose=True)
